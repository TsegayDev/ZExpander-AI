import { z } from 'zod';
import { callGeminiModel } from '../utils';

// ─────────────────────────────────────────────────────────────────────────────
// Schemas
// ─────────────────────────────────────────────────────────────────────────────

export const AIDetectionInputSchema = z.object({
  text: z.string().describe('The input text to analyze for AI generation.'),
  model: z.string().describe('The AI model to use for analysis.'),
});
export type AIDetectionInput = z.infer<typeof AIDetectionInputSchema>;

export const SentenceAnalysisSchema = z.object({
  text: z.string().describe('The sentence text.'),
  score: z
    .number()
    .min(0)
    .max(100)
    .describe('AI probability for this specific sentence (0=Human, 100=AI).'),
  flags: z
    .array(z.string())
    .optional()
    .describe('Specific AI markers detected in this sentence.'),
});

export const WritingPatternSchema = z.object({
  name: z.string().describe('Name of the writing pattern detected.'),
  present: z.boolean().describe('Whether this pattern is present in the text.'),
  description: z.string().describe('What this pattern means for the analysis.'),
});

export const AIDetectionOutputSchema = z.object({
  // ── Core verdict ──────────────────────────────────────────────────────────
  score: z
    .number()
    .min(0)
    .max(100)
    .describe('Overall AI probability score from 0 (Human) to 100 (AI).'),
  isAI: z
    .boolean()
    .describe('True if the overall score is >= 50, indicating likely AI origin.'),
  classification: z
    .enum(['human', 'mixed', 'ai'])
    .describe(
      'Three-way classification: "human" (0-30), "mixed" (31-69), "ai" (70-100).'
    ),
  confidence: z
    .number()
    .min(0)
    .max(100)
    .describe(
      'Confidence level of the verdict (0=very uncertain, 100=highly certain).'
    ),

  // ── Statistical estimates ─────────────────────────────────────────────────
  perplexityScore: z
    .number()
    .min(0)
    .max(100)
    .describe(
      'Estimated text predictability (0=highly unpredictable/human, 100=highly predictable/AI).'
    ),
  burstinessScore: z
    .number()
    .min(0)
    .max(100)
    .describe(
      'Sentence length variation score (0=monotone/AI, 100=highly varied/human).'
    ),
  readabilityScore: z
    .number()
    .min(0)
    .max(100)
    .describe(
      'Flesch-Kincaid style readability estimate (0=very hard, 100=very easy).'
    ),

  // ── Detailed analysis ─────────────────────────────────────────────────────
  aiMarkers: z
    .array(z.string())
    .describe('Specific AI-typical phrases, words, or patterns found in the text.'),
  writingPatterns: z
    .array(WritingPatternSchema)
    .describe('Analysis of key writing pattern signals that differentiate human vs AI text.'),
  sentences: z
    .array(SentenceAnalysisSchema)
    .describe('Per-sentence AI probability breakdown with optional flag annotations.'),

  // ── Summary ───────────────────────────────────────────────────────────────
  summary: z
    .string()
    .describe(
      'A concise, professional explanation of the detection verdict and key reasoning.'
    ),
});
export type AIDetectionOutput = z.infer<typeof AIDetectionOutputSchema>;

