// ─────────────────────────────────────────────────────────────────────────────
// Post-processing: normalize, clamp, validate derived fields
// ─────────────────────────────────────────────────────────────────────────────

function clamp(value: number, min = 0, max = 100): number {
  return Math.round(Math.min(max, Math.max(min, value)));
}

function deriveClassification(score: number): 'human' | 'mixed' | 'ai' {
  if (score <= 30) return 'human';
  if (score <= 69) return 'mixed';
  return 'ai';
}

function normalizeOutput(raw: AIDetectionOutput): AIDetectionOutput {
  const score = clamp(raw.score);
  const isAI = score >= 50;
  const classification = deriveClassification(score);

  return {
    ...raw,
    score,
    isAI,
    classification,
    confidence: clamp(raw.confidence),
    perplexityScore: clamp(raw.perplexityScore),
    burstinessScore: clamp(raw.burstinessScore),
    readabilityScore: clamp(raw.readabilityScore),

    // Ensure aiMarkers is always an array
    aiMarkers: Array.isArray(raw.aiMarkers) ? raw.aiMarkers : [],

    // Normalize writingPatterns
    writingPatterns: Array.isArray(raw.writingPatterns)
      ? raw.writingPatterns.map((p) => ({
        name: p.name ?? 'Unknown Pattern',
        present: Boolean(p.present),
        description: p.description ?? '',
      }))
      : [],

    // Normalize per-sentence scores
    sentences: Array.isArray(raw.sentences)
      ? raw.sentences.map((s) => ({
        text: s.text ?? '',
        score: clamp(s.score),
        flags: Array.isArray(s.flags) ? s.flags : [],
      }))
      : [],

    summary: raw.summary ?? 'Analysis complete.',
  };
}

// ─────────────────────────────────────────────────────────────────────────────
// Public API
// ─────────────────────────────────────────────────────────────────────────────

export async function detectAI(input: AIDetectionInput): Promise<AIDetectionOutput> {
  const output = await callGeminiModel({
    model: input.model,
    prompt: AI_DETECTION_PROMPT,
    input: input,
    outputSchema: AIDetectionOutputSchema,
    config: {
      temperature: 0.1,
      topP: 0.9,
    },
  });

  return normalizeOutput(output);
}

